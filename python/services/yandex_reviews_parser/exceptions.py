"""Типизированные ошибки парсера.

Разделяем три ситуации, которые по-разному обрабатываются на стороне API:
страница недоступна, изменилась разметка и техническая ошибка драйвера.
Пустой результат (организация без отзывов) ошибкой не считается.
"""


class ParserError(Exception):
    """Базовая ошибка парсинга с сообщением, пригодным для показа пользователю."""

    message = "Не удалось получить данные организации."

    def __init__(self, message: str | None = None):
        super().__init__(message or self.message)
        self.message = message or self.message


class PageUnavailableError(ParserError):
    """Карточка организации не загрузилась или не существует."""

    message = "Организация не найдена или страница недоступна."


class MarkupChangedError(ParserError):
    """Страница открылась, но ожидаемых элементов нет — вероятно, поменялась вёрстка."""

    message = "Не удалось разобрать страницу: изменилась разметка Яндекс.Карт."


class DriverError(ParserError):
    """Не удалось запустить браузер или открыть страницу."""

    message = "Сервис парсинга временно недоступен."
